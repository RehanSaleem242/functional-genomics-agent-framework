# PRIMARY REPORT MODEL - Composite Variant Functional Impact Report
# ============================================================================

class VariantFunctionalImpactReport(BaseModel):
    """
    Top-level variant functional impact report.
    
    This is the primary output schema for the genomic-analyst agent.
    Every field is strictly typed and validated per workspace Rule 2.
    
    No natural language commentary is allowed in this schema.
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True,
        json_schema_extra={
            "title": "Variant Functional Impact Report",
            "description": "Clinical-grade variant impact assessment with strict data types",
            "examples": [
                {
                    "metadata": {
                        "analysis_id": "BRCA1-VUS-001_20260602154656",
                        "variant_id": "BRCA1-VUS-001",
                        "timestamp": "2026-06-02T15:46:56Z",
                        "assembly": "hg38",
                        "schema_version": "1.0"
                    },
                    "input": {
                        "coordinate": "chr17:43044295A>G",
                        "context_window_kb": 1000,
                        "prediction_types": ["chromatin_accessibility", "expression_delta"]
                    },
                    "results": {
                        "chromatin_impact": {
                            "disruption_score": 0.8700,
                            "confidence": 0.9200,
                            "peak_proximity": "OVERLAPPING",
                            "affected_track_count": 3
                        },
                        "expression_impact": {
                            "delta_mean_log2fc": -1.4500,
                            "delta_max_log2fc": -2.3000,
                            "tissues_affected": ["heart", "brain"],
                            "confidence": 0.7800
                        },
                        "combined_risk_score": 0.7100,
                        "risk_category": "HIGH_RISK",
                        "validation_status": "VALID",
                        "missing_tracks": []
                    },
                    "audit": {
                        "input_sha256": "4a3f9d8e2c1b7a5f9e3c2b1a0f9e8d7c6b5a4f3e2d1c0b9a8f7e6d5c4b3a2f1",
                        "execution_duration_seconds": 16,
                        "data_sources": ["dnase_hg38", "gtex_expression_v8"]
                    }
                }
            ]
        }
    )
    
    metadata: VariantReportMetadata = Field(
        ...,
        description="Report metadata: IDs, timestamps, versioning"
    )
    
    input: VariantInputMetadata = Field(
        ...,
        description="Analysis input parameters"
    )
    
    results: dict = Field(
        ...,
        description="Analysis results container"
    )
    
    audit: AuditMetadata = Field(
        ...,
        description="Audit trail: input fingerprint, execution time, data sources"
    )
    
    @field_validator("results")
    @classmethod
    def validate_results_structure(cls, v: dict) -> dict:
        """Validate results dictionary contains required keys."""
        required_keys = {
            "chromatin_impact",
            "expression_impact",
            "combined_risk_score",
            "risk_category",
            "validation_status",
            "missing_tracks"
        }
        
        missing = required_keys - set(v.keys())
        if missing:
            raise ValueError(f"results missing required keys: {missing}")
        
        # Validate chromatin_impact structure
        chromatin = v.get("chromatin_impact", {})
        chromatin_required = {"disruption_score", "confidence", "peak_proximity", "affected_track_count"}
        chromatin_missing = chromatin_required - set(chromatin.keys())
        if chromatin_missing:
            raise ValueError(f"chromatin_impact missing keys: {chromatin_missing}")
        
        # Validate expression_impact structure
        expression = v.get("expression_impact", {})
        expression_required = {"delta_mean_log2fc", "delta_max_log2fc", "tissues_affected", "confidence"}
        expression_missing = expression_required - set(expression.keys())
        if expression_missing:
            raise ValueError(f"expression_impact missing keys: {expression_missing}")
        
        # Validate combined_risk_score bounds
        risk_score = v.get("combined_risk_score")
        if not isinstance(risk_score, (int, float)) or not (0.0 <= risk_score <= 1.0):
            raise ValueError(f"combined_risk_score must be float in [0.0, 1.0], got {risk_score}")
        
        # Validate risk_category
        risk_cat = v.get("risk_category")
        if risk_cat not in ["LOW_RISK", "MODERATE_RISK", "HIGH_RISK"]:
            raise ValueError(f"risk_category must be LOW_RISK, MODERATE_RISK, or HIGH_RISK, got {risk_cat}")
        
        # Validate validation_status
        val_status = v.get("validation_status")
        if val_status not in ["VALID", "INVALID_SCHEMA", "DATA_GAP"]:
            raise ValueError(f"validation_status must be VALID, INVALID_SCHEMA, or DATA_GAP, got {val_status}")
        
        # Validate missing_tracks
        missing_tracks = v.get("missing_tracks", [])
        if not isinstance(missing_tracks, list):
            raise ValueError(f"missing_tracks must be a list, got {type(missing_tracks)}")
        
        return v


