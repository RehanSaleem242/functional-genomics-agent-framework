def validate_report_file(file_path: str, schema_version: str = "1.0", halt_on_error: bool = True) -> dict:
    """
    Validate a variant report JSON file against the Pydantic schema.
    
    Args:
        file_path: Path to the variant report JSON file
        schema_version: Expected schema version (default: "1.0")
        halt_on_error: Exit with error code on validation failure (default: True)
    
    Returns:
        dict: Validation result with keys:
            - success: bool
            - message: str
            - errors: list of error strings (if any)
            - report: VariantFunctionalImpactReport (if valid)
    """
    
    result = {
        "success": False,
        "message": "",
        "errors": [],
        "report": None
    }
    
    # Step 1: Check file exists
    if not Path(file_path).exists():
        result["message"] = f"File not found: {file_path}"
        result["errors"].append(result["message"])
        return result
    
    # Step 2: Load JSON
    try:
        with open(file_path, "r") as f:
            report_data = json.load(f)
    except json.JSONDecodeError as e:
        result["message"] = f"Invalid JSON: {str(e)}"
        result["errors"].append(result["message"])
        return result
    except Exception as e:
        result["message"] = f"Error reading file: {str(e)}"
        result["errors"].append(result["message"])
        return result
    
    # Step 3: Validate against Pydantic schema
    try:
        report = VariantFunctionalImpactReport(**report_data)
        
        # Additional: Check schema version
        if report.metadata.schema_version != schema_version:
            result["errors"].append(
                f"Schema version mismatch: expected {schema_version}, got {report.metadata.schema_version}"
            )
            result["message"] = "Schema version validation failed"
            return result
        
        result["success"] = True
        result["message"] = f"✓ Report is valid and compliant with schema v{schema_version}"
        result["report"] = report
        
    except Exception as e:
        result["message"] = f"Validation failed: {str(e)}"
        result["errors"].append(str(e))
        
        # Extract detailed errors if available
        if hasattr(e, "errors"):
            for err in e.errors():
                error_msg = f"  - {err['loc']}: {err['msg']}"
                result["errors"].append(error_msg)
    
    return result


def main():
    """
    CLI entry point for validating variant reports.
    
    Usage:
        python validate_pydantic_schema.py --report-file <path> [--schema-version <v>] [--halt-on-error true|false]
    
    Example:
        python validate_pydantic_schema.py --report-file data/reports/BRCA1-VUS-001.json --schema-version 1.0 --halt-on-error true
    """
    
    import argparse
    
    parser = argparse.ArgumentParser(
        description="Validate variant functional impact reports against Pydantic schema"
    )
    parser.add_argument(
        "--report-file",
        required=True,
        help="Path to the variant report JSON file"
    )
    parser.add_argument(
        "--schema-version",
        default="1.0",
        help="Expected schema version (default: 1.0)"
    )
    parser.add_argument(
        "--halt-on-error",
        default="true",
        choices=["true", "false"],
        help="Exit with error code on validation failure (default: true)"
    )
    
    args = parser.parse_args()
    halt_on_error = args.halt_on_error.lower() == "true"
    
    # Validate report
    result = validate_report_file(
        file_path=args.report_file,
        schema_version=args.schema_version,
        halt_on_error=halt_on_error
    )
    
    # Output results
    print("")
    print("=" * 70)
    print("VARIANT REPORT VALIDATION RESULT")
    print("=" * 70)
    print("")
    print(result["message"])
    print("")
    
    if not result["success"]:
        print("VALIDATION ERRORS:")
        for error in result["errors"]:
            print(error)
        print("")
        if halt_on_error:
            sys.exit(1)
    else:
        print("Report Structure:")
        print(f"  Analysis ID: {result['report'].metadata.analysis_id}")
        print(f"  Variant ID:  {result['report'].metadata.variant_id}")
        print(f"  Assembly:    {result['report'].metadata.assembly.value}")
        print(f"  Timestamp:   {result['report'].metadata.timestamp.isoformat()}")
        print("")
        print(f"Risk Category: {result['report'].results['risk_category']}")
        print(f"Risk Score:    {result['report'].results['combined_risk_score']:.4f}")
        print(f"Validation:    {result['report'].results['validation_status']}")
        print("")
        if halt_on_error:
            sys.exit(0)


if __name__ == "__main__":
    main()
