#!/usr/bin/env python3
"""
Pydantic Schema Validation for Variant Functional Impact Reports

This module defines strict, clinical-grade Pydantic models for validating
variant impact reports generated by the genomic-analyst agent. All outputs
assessing variant biological impact must conform to these models.

Workspace Rule 2 Enforcement: Strict Data Type Output - no natural language allowed.
"""

import json
import sys
from enum import Enum
from typing import List, Optional
from datetime import datetime
from pathlib import Path

from pydantic import BaseModel, Field, field_validator, ConfigDict


# ============================================================================
# ENUMERATIONS - Categorical/Strict Type System
# ============================================================================

class PeakProximityFlag(str, Enum):
    """Categorical: Distance relationship to chromatin accessibility peaks."""
    FAR = "FAR"                        # >50bp from peak boundary
    NEAR = "NEAR"                      # ±50bp from peak boundary
    OVERLAPPING = "OVERLAPPING"        # Within peak region


class RiskCategory(str, Enum):
    """Categorical: Composite pathogenicity risk classification."""
    LOW_RISK = "LOW_RISK"              # Combined risk score < 0.4
    MODERATE_RISK = "MODERATE_RISK"    # Combined risk score 0.4-0.7
    HIGH_RISK = "HIGH_RISK"            # Combined risk score > 0.7


class ValidationStatus(str, Enum):
    """Categorical: Schema and data completeness status."""
    VALID = "VALID"                        # All required data present and valid
    INVALID_SCHEMA = "INVALID_SCHEMA"      # Pydantic validation failed
    DATA_GAP = "DATA_GAP"                  # Some functional tracks unavailable


class AssemblyContext(str, Enum):
    """Categorical: Genomic assembly version (hg38-only in this workspace)."""
    HG38 = "hg38"                          # GRCh38.p14 (required and only allowed)


# ============================================================================
# FLOATING-POINT METRICS - Strictly Bounded Numerical Values
# ============================================================================

class ChromatinImpact(BaseModel):
    """
    Chromatin accessibility disruption metrics.
    
    All scores are bounded to [0.0, 1.0] scale:
    - 0.0 = no disruption detected
    - 1.0 = complete loss of accessibility
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True,
        json_schema_extra={
            "description": "Predicted chromatin disruption metrics for the variant"
        }
    )
    
    disruption_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        decimal_places=4,
        description="Chromatin accessibility disruption magnitude (0.0=none, 1.0=complete loss)"
    )
    
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        decimal_places=4,
        description="Model confidence in disruption prediction (0.0=low, 1.0=high)"
    )
    
    peak_proximity: PeakProximityFlag = Field(
        ...,
        description="Spatial relationship to known chromatin accessibility peaks"
    )
    
    affected_track_count: int = Field(
        ...,
        ge=0,
        description="Number of distinct chromatin marks/tracks disrupted by variant"
    )
    
    @field_validator("disruption_score", "confidence")
    @classmethod
    def validate_score_precision(cls, v: float) -> float:
        """Enforce 4 decimal places on all scores."""
        if v is not None:
            rounded = round(v, 4)
            if abs(v - rounded) > 1e-5:
                raise ValueError(f"Score must have ≤4 decimal places: {v}")
        return v


class ExpressionImpact(BaseModel):
    """
    Gene expression disruption metrics across tissue contexts.
    
    Expression deltas are unbounded log-fold-change values:
    - Negative: decreased expression
    - Positive: increased expression
    - Typical range: [-5.0, +5.0] for biological systems
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True,
        json_schema_extra={
            "description": "Predicted expression change metrics for the variant"
        }
    )
    
    delta_mean_log2fc: float = Field(
        ...,
        description="Mean log-fold-change in expression across tissues (unbounded)"
    )
    
    delta_max_log2fc: float = Field(
        ...,
        description="Maximum absolute log-fold-change across all tissues (unbounded)"
    )
    
    tissues_affected: List[str] = Field(
        ...,
        min_length=1,
        description="List of tissues/cell types showing expression change |delta| > 0.5"
    )
    
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        decimal_places=4,
        description="Model confidence in expression prediction (0.0=low, 1.0=high)"
    )
    
    @field_validator("tissues_affected")
    @classmethod
    def validate_tissue_list(cls, v: List[str]) -> List[str]:
        """Tissue list must be non-empty and contain valid tissue names."""
        if not v:
            raise ValueError("tissues_affected list cannot be empty")
        if len(set(v)) != len(v):
            raise ValueError("tissues_affected contains duplicate entries")
        for tissue in v:
            if not isinstance(tissue, str) or len(tissue) == 0:
                raise ValueError(f"Invalid tissue name: {tissue}")
        return v


class AuditMetadata(BaseModel):
    """
    Data integrity and reproducibility audit information.
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True
    )
    
    input_sha256: str = Field(
        ...,
        pattern=r"^[a-f0-9]{64}$",
        description="SHA256 hash of input variant file (hex, 64 chars)"
    )
    
    execution_duration_seconds: int = Field(
        ...,
        ge=0,
        description="Total execution time in seconds"
    )
    
    data_sources: List[str] = Field(
        ...,
        min_length=1,
        description="List of functional track databases queried (e.g., dnase_hg38, gtex_v8)"
    )
    
    @field_validator("data_sources")
    @classmethod
    def validate_data_sources(cls, v: List[str]) -> List[str]:
        """Data sources must be non-empty and contain valid identifiers."""
        if not v:
            raise ValueError("data_sources list cannot be empty")
        for source in v:
            if not isinstance(source, str) or len(source) == 0:
                raise ValueError(f"Invalid data source: {source}")
        return v


class VariantReportMetadata(BaseModel):
    """
    Report metadata: timing, versioning, identifiers.
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True
    )
    
    analysis_id: str = Field(
        ...,
        min_length=5,
        max_length=100,
        description="Unique identifier for this analysis (e.g., BRCA1-VUS-001_20260602154656)"
    )
    
    variant_id: str = Field(
        ...,
        min_length=3,
        max_length=100,
        description="Clinical variant identifier"
    )
    
    timestamp: datetime = Field(
        ...,
        description="ISO-8601 analysis timestamp"
    )
    
    assembly: AssemblyContext = Field(
        default=AssemblyContext.HG38,
        description="Genomic assembly version (hg38-only)"
    )
    
    schema_version: str = Field(
        default="1.0",
        pattern=r"^\d+\.\d+$",
        description="Schema version for this report (semver format)"
    )
    
    @field_validator("assembly")
    @classmethod
    def enforce_hg38(cls, v: AssemblyContext) -> AssemblyContext:
        """Enforce hg38 assembly - workspace rule."""
        if v != AssemblyContext.HG38:
            raise ValueError(
                f"Only hg38 assembly is permitted in this workspace. Received: {v}"
            )
        return v


class VariantInputMetadata(BaseModel):
    """
    Input analysis parameters.
    """
    
    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_default=True
    )
    
    coordinate: str = Field(
        ...,
        pattern=r"^chr([1-9]|[12][0-9]|3[0-2]|X|Y|M):[0-9]+[ATCG]>[ATCG]$",
        description="Variant coordinate (HGVS format: chrN:positionREF>ALT)"
    )
    
    context_window_kb: int = Field(
        default=1000,
        ge=100,
        le=5000,
        description="Sequence context window in kilobases (default 1000)"
    )
    
    prediction_types: List[str] = Field(
        default=["chromatin_accessibility", "expression_delta"],
        description="Types of predictions performed"
    )


