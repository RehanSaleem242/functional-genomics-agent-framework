# 🚀 Execution Trigger
if st.button("🚀 Analyze Variant & Execute Guardrail Pipeline", type="primary"):
    with st.spinner("Invoking Genomic Agent Loop & Processing 1Mb Context Window..."):
        
        # 1. Run the backend pipeline to fetch the generated report
        report, path_to_file = run_agentic_pipeline(gene_input, coord_input)
        
        if report is None:
            st.stop()
        
        st.subheader("🛡️ Triggering Runtime Guardrail Hooks")
        
        # 2. Visually trigger your CLI Pydantic Validation Script via subprocess
        # This streams the actual terminal verification output onto your web page!
        cmd = ["python", "tests/validate_pydantic_schema.py", "--report-file", path_to_file]
        result = subprocess.run(cmd, capture_output=True, text=True)
        
        st.info(f"Validating report: `{os.path.basename(path_to_file)}`")
        
        # 3. Render Status Based on Hook Output
        if result.returncode == 0:
            st.success("✅ HOOK VERIFICATION PASSED: Report perfectly matches Pydantic constraints and hg38 assembly rules.")
            
            # Show the beautiful data metrics
            st.markdown("### 📊 Automated Quantitative Metrics Summary")
            c1, c2, c3, c4 = st.columns(4)
            results_node = report.get("results", {})
            
            c1.metric(
                "Chromatin Accessibility Δ", 
                f"{results_node.get('chromatin_accessibility_delta', 0.0):.4f}"
            )
            c2.metric(
                "RNA-Seq Perturbation", 
                f"{results_node.get('predicted_rna_seq_perturbation', 0.0):+.4f}"
            )
            c3.metric(
                "Risk Category", 
                results_node.get('risk_category', 'UNKNOWN')
            )
            c4.metric(
                "Confidence Score", 
                f"{results_node.get('confidence_score', 0.0):.2%}"
            )
            
            # Print the verified JSON payload
            st.markdown("#### ✓ Cryptographically Verified Payload")
            st.json(report)
            
            # Show audit trail info if available
            if "audit_trail" in report:
                st.markdown("#### 🔐 Cryptographic Audit Trail")
                audit = report["audit_trail"]
                st.caption(f"SHA256 Fingerprint: `{audit.get('file_hash', 'N/A')[:16]}...`")
                st.caption(f"Timestamp: `{audit.get('timestamp', 'N/A')}`")
            
        else:
            st.error("🚨 HOOK VERIFICATION FAILED: Critical LLM Hallucination Detected and Quarantined!")
            st.markdown("#### ⚠️ Terminal Validation Stack Trace (Reason for Block):")
            error_output = result.stderr if result.stderr else result.stdout
            st.code(error_output, language="bash")
            
            st.warning(
                "⛔ This report has been safely routed to `data/.quarantine/` and "
                "blocked from clinical pipeline integration. No contamination occurred."
            )

